package com.cnethuka.kegare;

import com.mojang.logging.LogUtils;
import com.cnethuka.kegare.config.KegareClientConfig;
import com.cnethuka.kegare.config.KegareConfigMigration;
import com.cnethuka.kegare.config.KegareServerConfig;
import com.cnethuka.kegare.data.KegareDataGen;
import com.cnethuka.kegare.network.KegareNetwork;
import com.cnethuka.kegare.registry.KegareAttachments;
import com.cnethuka.kegare.registry.KegareItems;
import com.cnethuka.kegare.registry.KegareRegistries;
import com.cnethuka.kegare.innate_technique.rime.Rime;
import com.cnethuka.kegare.innatetechnique.test.TestInnateTechniques;
import com.cnethuka.kegare.trait.KegareTraits;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.fml.ModContainer;
import net.neoforged.fml.common.Mod;
import net.neoforged.fml.config.ModConfig;
import org.slf4j.Logger;

/**
 * Kegare mod entry point.
 * <p>
 * Naming rule: code IDs match the display names ({@code malice} = Malice, {@code innate_technique} = Innate Technique,
 * {@code dominion} = Dominion, {@code severed} = Severed). Every player-facing string still lives only in the lang file
 * (generated by {@code KegareLanguageProvider}). "Kegare" is the mod name, reserved for future hostile spirit mobs.
 */
@Mod(Kegare.MODID)
public final class Kegare {
    public static final String MODID = "kegare";
    public static final Logger LOGGER = LogUtils.getLogger();

    public Kegare(IEventBus modBus, ModContainer container) {
        // Registries first: entries below are registered into them.
        KegareRegistries.register(modBus);
        KegareAttachments.ATTACHMENT_TYPES.register(modBus);
        KegareItems.ITEMS.register(modBus);
        com.cnethuka.kegare.registry.KegareCreativeTab.TABS.register(modBus);
        com.cnethuka.kegare.sound.KegareSounds.SOUND_EVENTS.register(modBus);
        KegareTraits.TRAITS.register(modBus);
        Rime.register(modBus);
        com.cnethuka.kegare.innate_technique.swap.Swap.register(modBus);
        com.cnethuka.kegare.innate_technique.puppet_manipulation.PuppetManipulation.register(modBus);
        com.cnethuka.kegare.innate_technique.time_manipulation.TimeManipulation.register(modBus);
        com.cnethuka.kegare.melee.MeleeLayer.init(modBus);
        com.cnethuka.kegare.severed.Severed.init(modBus); // a Severed player's body (DESIGN §3.27)
        com.cnethuka.kegare.rmt.Rmt.init(modBus); // registers Reverse Malice Technique as a shared ability
        com.cnethuka.kegare.reinforcement.Reinforcement.init(); // Reinforcement, every Malice user's (DESIGN §3.16)
        com.cnethuka.kegare.backgroundtask.BackgroundTaskEvents.init(); // Background Tasks (DESIGN §3.31)
        com.cnethuka.kegare.sixeyes.SixEyes.init(); // Six Eyes' gameplay (DESIGN §3.32)
        com.cnethuka.kegare.fists.Fists.init(modBus); // Reinforced Fists, every Malice user's (DESIGN §3.28)
        com.cnethuka.kegare.sight.DelayedSight.init(); // too fast for the eye: Blur and Accelerate seen where they were (DESIGN §3.30)
        com.cnethuka.kegare.impact.Impacts.init(); // hit-stop, shake, flashes and impact frames (DESIGN §3.23)
        com.cnethuka.kegare.battledamage.BattleDamage.init(); // big hits break the world (DESIGN §3.24)
        TestInnateTechniques.INNATE_TECHNIQUES.register(modBus); // TEST CONTENT

        com.cnethuka.kegare.progression.Progression.init();
        modBus.addListener(KegareNetwork::register);
        modBus.addListener(KegareDataGen::gather);

        modBus.addListener(KegareConfigMigration::onConfigLoading);
        modBus.addListener(com.cnethuka.kegare.database.LoginTask::register);
        com.cnethuka.kegare.database.StatEvents.init();
        container.registerConfig(ModConfig.Type.SERVER, KegareServerConfig.SPEC);
        container.registerConfig(ModConfig.Type.CLIENT, KegareClientConfig.SPEC);
    }

    public static ResourceLocation id(String path) {
        return ResourceLocation.fromNamespaceAndPath(MODID, path);
    }
}
