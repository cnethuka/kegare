package com.cnethuka.kegare;

import com.mojang.logging.LogUtils;
import com.cnethuka.kegare.config.KegareClientConfig;
import com.cnethuka.kegare.config.KegareServerConfig;
import com.cnethuka.kegare.data.KegareDataGen;
import com.cnethuka.kegare.network.KegareNetwork;
import com.cnethuka.kegare.registry.KegareAttachments;
import com.cnethuka.kegare.registry.KegareItems;
import com.cnethuka.kegare.registry.KegareRegistries;
import com.cnethuka.kegare.technique.test.TestTechniques;
import com.cnethuka.kegare.trait.KegareTraits;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.fml.ModContainer;
import net.neoforged.fml.common.Mod;
import net.neoforged.fml.config.ModConfig;
import org.slf4j.Logger;

/**
 * Kegare mod entry point.
 * <p>
 * Naming rule: code uses neutral IDs ({@code ce}, {@code technique}, {@code domain}, {@code trait}).
 * Every player-facing name lives in the lang file (generated by {@code KegareLanguageProvider}).
 */
@Mod(Kegare.MODID)
public final class Kegare {
    public static final String MODID = "kegare";
    public static final Logger LOGGER = LogUtils.getLogger();

    public Kegare(IEventBus modBus, ModContainer container) {
        // Registries first: entries below are registered into them.
        KegareRegistries.register(modBus);
        KegareAttachments.ATTACHMENT_TYPES.register(modBus);
        KegareItems.ITEMS.register(modBus);
        KegareTraits.TRAITS.register(modBus);
        TestTechniques.TECHNIQUES.register(modBus); // TEST CONTENT

        modBus.addListener(KegareItems::addToCreativeTabs);
        modBus.addListener(KegareNetwork::register);
        modBus.addListener(KegareDataGen::gather);

        container.registerConfig(ModConfig.Type.SERVER, KegareServerConfig.SPEC);
        container.registerConfig(ModConfig.Type.CLIENT, KegareClientConfig.SPEC);
    }

    public static ResourceLocation id(String path) {
        return ResourceLocation.fromNamespaceAndPath(MODID, path);
    }
}
